/**
 * Generates supabase/seed.sql from scripts/fixtures/seed-data.ts.
 *   npm run seed:generate
 * seed.sql is committed, so you only need this after editing the fixtures.
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { LETTERS, PATIENTS, STAFF } from "./fixtures/seed-data";
import { documentPath, queryLetterPath } from "./fixtures/paths";

const q = (v: unknown): string => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return v ? "true" : "false";
  return `'${String(v).replace(/'/g, "''")}'`;
};
const j = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`;
const addSec = (iso: string, s: number) => new Date(new Date(iso).getTime() + s * 1000).toISOString();
const mask = (phone: string) => `${phone.slice(0, 3)} ••••• •${phone.slice(-3)}`;
const maskEmail = (e: string) => `${e.split("@")[0].slice(0, 2)}•••@${e.split("@")[1]}`;

const out: string[] = [];
out.push(`-- AUTO-GENERATED by scripts/generate-seed.ts — edit the fixtures, not this file.
-- Demo staff logins (local only!):
${STAFF.map((s) => `--   ${s.role.padEnd(5)} ${s.email} / ${s.password}`).join("\n")}
`);

// ---------------------------------------------------------------- staff (auth + profile)
out.push("-- Staff auth users");
for (const s of STAFF) {
  out.push(`insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,
  raw_app_meta_data, raw_user_meta_data, created_at, updated_at,
  confirmation_token, email_change, email_change_token_new, recovery_token)
values ('00000000-0000-0000-0000-000000000000', ${q(s.id)}, 'authenticated', 'authenticated', ${q(s.email)},
  extensions.crypt(${q(s.password)}, extensions.gen_salt('bf')), now(),
  '{"provider":"email","providers":["email"]}', ${j({ full_name: s.full_name })}, now(), now(), '', '', '', '');
insert into auth.identities (id, provider_id, user_id, identity_data, provider, last_sign_in_at, created_at, updated_at)
values (gen_random_uuid(), ${q(s.id)}, ${q(s.id)}, ${j({ sub: s.id, email: s.email, email_verified: true })}, 'email', now(), now(), now());
insert into public.staff_users (id, role, full_name, email) values (${q(s.id)}, ${q(s.role)}, ${q(s.full_name)}, ${q(s.email)});`);
}

// ---------------------------------------------------------------- patients + documents
out.push("\n-- Patients");
for (const p of PATIENTS) {
  out.push(`insert into public.patients (id, patient_code, full_name, phone, email, policy_number, insurer, assigned_agent_id)
values (${q(p.id)}, ${q(p.code)}, ${q(p.full_name)}, ${q(p.phone)}, ${q(p.email)}, ${q(p.policy_number)}, ${q(p.insurer)}, ${q(p.agent)});`);
}

out.push("\n-- Documents (files are uploaded by `npm run seed:storage`)");
for (const p of PATIENTS) {
  for (const d of p.docs) {
    const extracted = {
      doc_type: d.type,
      patient_name: p.full_name,
      hospital: d.hospital,
      doc_date: d.date,
      amount: d.amount,
      confidence: d.confidence,
      legible: d.facts.legible ?? true,
      key_facts: d.facts,
      model: "seed",
    };
    const uploaded = addSec(`${d.date}T12:00:00+05:30`, 86400);
    out.push(`insert into public.documents (id, patient_id, doc_type, file_path, original_name, mime_type, size_bytes, extracted_json,
  doc_date, hospital, amount, confidence, classification_status, uploaded_at)
values (${q(d.id)}, ${q(p.id)}, ${q(d.type)}, ${q(documentPath(p.id, d.id, d.name))}, ${q(d.name)},
  ${q(d.name.endsWith(".pdf") ? "application/pdf" : "image/jpeg")}, null, ${j(extracted)},
  ${q(d.date)}, ${q(d.hospital)}, ${q(d.amount)}, ${q(d.confidence)}, 'CLASSIFIED', ${q(uploaded)});`);
  }
}

// ---------------------------------------------------------------- query letters, points, events, messages
out.push("\n-- Query letters");
const STEPS = ["RECEIVED", "READ", "EXTRACT", "MATCH", "REVIEW_GATE", "COMPOSE", "SEND_WHATSAPP", "SEND_EMAIL", "DONE"] as const;
const DUR: Record<string, number> = { RECEIVED: 0, READ: 4200, EXTRACT: 3100, MATCH: 3900, REVIEW_GATE: 5, COMPOSE: 12, SEND_WHATSAPP: 850, SEND_EMAIL: 610, DONE: 0 };

for (const l of LETTERS) {
  const p = PATIENTS.find((x) => x.id === l.patient_id)!;
  const processed = l.status !== "RECEIVED";
  const t = (s: number) => q(addSec(l.received_at, s));
  const reviewReason = l.points.some((x) => x.needs_review) ? "1 point below confidence threshold (0.6)" : null;
  out.push(`insert into public.query_letters (id, patient_id, file_path, original_name, status, current_step, review_reason,
  raw_text, page_count, received_at, read_at, analysed_at, sent_at, processed_at)
values (${q(l.id)}, ${q(l.patient_id)}, ${q(queryLetterPath(l.patient_id, l.id, l.file_name))}, ${q(l.file_name)},
  ${q(l.status)}, ${q(processed ? "DONE" : "RECEIVED")}, ${q(reviewReason)},
  ${processed ? q(l.lines.join("\n")) : "null"}, ${processed ? 1 : "null"}, ${q(l.received_at)},
  ${processed ? t(5) : "null"}, ${processed ? t(12) : "null"}, ${processed ? t(14) : "null"}, ${processed ? t(14) : "null"});`);

  // pipeline events
  let clock = 0;
  out.push(`insert into public.query_letter_events (query_letter_id, step, status, detail, duration_ms, created_at) values`);
  const ev: string[] = [`(${q(l.id)}, 'RECEIVED', 'SUCCEEDED', 'Letter uploaded', 0, ${t(0)})`];
  if (processed) {
    for (const s of STEPS.slice(1)) {
      clock += DUR[s] / 1000;
      const detail =
        s === "READ" ? "1 page read" :
        s === "EXTRACT" ? `${l.points.length} points found` :
        s === "MATCH" ? `${l.points.filter((x) => x.decision === "NEED_FROM_PATIENT").length} needed from patient` :
        s === "REVIEW_GATE" ? (reviewReason ?? "All points confident") :
        s === "DONE" ? l.status : null;
      ev.push(`(${q(l.id)}, ${q(s)}, ${q(s === "REVIEW_GATE" && reviewReason ? "FAILED" : "SUCCEEDED")}, ${q(detail)}, ${DUR[s]}, ${t(clock)})`);
    }
  }
  out.push(ev.join(",\n") + ";");

  for (const pt of l.points) {
    out.push(`insert into public.query_points (query_letter_id, point_no, point_text, insurer_ask, needed_doc_type, decision,
  matched_document_id, reason, confidence, needs_review)
values (${q(l.id)}, ${pt.point_no}, ${q(pt.point_text)}, ${q(pt.insurer_ask)}, ${q(pt.needed_doc_type)}, ${q(pt.decision)},
  ${q(pt.matched_document_id)}, ${q(pt.reason)}, ${pt.confidence}, ${q(!!pt.needs_review)});`);
  }

  for (const m of l.messages ?? []) {
    const to = m.channel === "WHATSAPP" ? mask(p.phone) : maskEmail(p.email);
    const pid = m.channel === "WHATSAPP" ? `SM${l.id.replace(/-/g, "").slice(-16)}` : `re_${l.id.slice(-12)}`;
    out.push(`insert into public.messages (patient_id, query_letter_id, channel, kind, revision, idempotency_key, status, to_address,
  subject, body, provider_message_id, attempts, created_at, sent_at)
values (${q(p.id)}, ${q(l.id)}, ${q(m.channel)}, 'AUTO', 0, ${q(`${l.id}:${m.channel}:0`)}, ${q(m.status)}, ${q(to)},
  ${q(m.subject ?? null)}, ${q(m.body)}, ${q(pid)}, 1, ${t(13)}, ${t(14)});`);
  }
}

const target = join(__dirname, "..", "supabase", "seed.sql");
writeFileSync(target, out.join("\n") + "\n");
console.log(`wrote ${target}`);
